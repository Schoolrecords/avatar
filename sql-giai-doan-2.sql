-- 1) BẢNG GIÁO VIÊN
create table if not exists public.giao_vien(
  id bigint generated by default as identity primary key,
  ten text not null, ns text, td text, dc text, sdt text, mon text,
  coso_id int not null,
  created_at timestamptz default now()
);
create index if not exists gv_coso_idx on public.giao_vien(coso_id);

-- 2) BẢNG LỚP HỌC
create table if not exists public.lop_hoc(
  id bigint generated by default as identity primary key,
  lop text not null, gv text, siso int default 0, mon text,
  coso_id int not null,
  created_at timestamptz default now()
);
create index if not exists lh_coso_idx on public.lop_hoc(coso_id);

-- 3) KHÓA HÀNG (RLS): admin = mọi cơ sở; owner = đúng cơ sở của mình
alter table public.giao_vien enable row level security;
alter table public.lop_hoc   enable row level security;

drop policy if exists giao_vien_sel on public.giao_vien;
drop policy if exists giao_vien_ins on public.giao_vien;
drop policy if exists giao_vien_upd on public.giao_vien;
drop policy if exists giao_vien_del on public.giao_vien;
create policy giao_vien_sel on public.giao_vien for select to authenticated using (my_role()='admin' or coso_id=my_coso());
create policy giao_vien_ins on public.giao_vien for insert to authenticated with check (my_role()='admin' or coso_id=my_coso());
create policy giao_vien_upd on public.giao_vien for update to authenticated using (my_role()='admin' or coso_id=my_coso()) with check (my_role()='admin' or coso_id=my_coso());
create policy giao_vien_del on public.giao_vien for delete to authenticated using (my_role()='admin' or coso_id=my_coso());

drop policy if exists lop_hoc_sel on public.lop_hoc;
drop policy if exists lop_hoc_ins on public.lop_hoc;
drop policy if exists lop_hoc_upd on public.lop_hoc;
drop policy if exists lop_hoc_del on public.lop_hoc;
create policy lop_hoc_sel on public.lop_hoc for select to authenticated using (my_role()='admin' or coso_id=my_coso());
create policy lop_hoc_ins on public.lop_hoc for insert to authenticated with check (my_role()='admin' or coso_id=my_coso());
create policy lop_hoc_upd on public.lop_hoc for update to authenticated using (my_role()='admin' or coso_id=my_coso()) with check (my_role()='admin' or coso_id=my_coso());
